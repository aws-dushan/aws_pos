-- One POS: rehearse usp_ONEPOS_PostReturn: bill INV-EBL-01-000325 (12.00, VISA, European Bakery Al Qusais) returned whole, as PSR51
-- REHEARSAL-RET-1 posted as POSBAKERY (the FACTS user One POS posts returns as). Everything is rolled back at the end: no PSR51 stays, no stock or accounts move. Run after
-- creating the procedure, and after PSR51's setup is fixed (DM_UD_LABEL8 = DEBIT, its payment methods' PM_SIGN = -1).
-- Check in the answers: the accounts reverse the bill's (sales 5000 and VAT 4107 debited, the customer AR credited, the card account
-- 2315 credited: money out), the stock comes back IN on the bill's batch, and ACTION_STATUS has usp_SAL_APPR_Posting.
SET XACT_ABORT OFF;
BEGIN TRANSACTION;

EXEC dbo.usp_ONEPOS_PostReturn @ClientID = N'POSBAKERY', @BodyXML = N'<data><CreditNote><CreditNoteNo>REHEARSAL-RET-1</CreditNoteNo><CreditNoteDate>2026-10-30</CreditNoteDate>
  <InvoiceNo>INV-EBL-01-000325</InvoiceNo><NetAmount>12.00</NetAmount><Reason>Rehearsal</Reason></CreditNote></data>';

-- What it made (inside the transaction), next to the bill's own entries.
SELECT SAL_DOCTYPE, SAL_DOCNO, SAL_NET_AMOUNT, SAL_VAT_AMOUNT, SAL_UD_LABEL3, SAL_UD_LABEL4, SAL_NARRATION, SAL_POSTED_BY FROM dbo.SALES_HEADER
WHERE (SAL_DOCTYPE = 'PSR51' AND SAL_DOCNO = 'REHEARSAL-RET-1') OR (SAL_DOCTYPE = 'POS51' AND SAL_DOCNO = 'INV-EBL-01-000325');
SELECT SALDET_DOCTYPE, SALDET_DOCSRNO, SALDET_STOCK_DOCNO, SALDET_QTY, SALDET_AMOUNT, SALDET_BATCH_DOCNO, SALDET_PREVIOUS_DOCTYPE, SALDET_PREVIOUS_DOCNO FROM dbo.SALES_DETAILS
WHERE SALDET_DOCTYPE = 'PSR51' AND SALDET_DOCNO = 'REHEARSAL-RET-1';
SELECT RD_DOCTYPE, RD_DOCNO, RD_RECEIPT_MODE, RD_AMOUNT FROM dbo.RECEIPT_DETAILS
WHERE (RD_DOCTYPE = 'PSR51' AND RD_DOCNO = 'REHEARSAL-RET-1') OR (RD_DOCTYPE = 'POS51' AND RD_DOCNO = 'INV-EBL-01-000325');
SELECT STTRN_DOCTYPE, STTRN_STOCK_DOCNO, STTRN_LOCATION_DOCNO, STTRN_QTY, STTRN_BATCH_DOCNO, STTRN_COST_RATE FROM dbo.STOCK_TRANSACTION
WHERE (STTRN_DOCTYPE = 'PSR51' AND STTRN_DOCNO = 'REHEARSAL-RET-1') OR (STTRN_DOCTYPE = 'POS51' AND STTRN_DOCNO = 'INV-EBL-01-000325');
SELECT ACTRN_DOCTYPE, ACTRN_DOCSRNO, ACTRN_AC_DOCNO, ACTRN_SUBLEDGER_DOCNO, ACTRN_AMOUNT FROM dbo.ACCOUNT_TRANSACTION
WHERE (ACTRN_DOCTYPE = 'PSR51' AND ACTRN_DOCNO = 'REHEARSAL-RET-1') OR (ACTRN_DOCTYPE = 'POS51' AND ACTRN_DOCNO = 'INV-EBL-01-000325') ORDER BY ACTRN_DOCTYPE, ACTRN_DOCSRNO;
SELECT ACTION_DOCNO, ACTION_KEY, ACTION_TYPE, ACTION_USER_DOCNO FROM dbo.ACTION_STATUS WHERE ACTION_DOCTYPE = 'PSR51' AND ACTION_DOCNO = 'REHEARSAL-RET-1';

IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
SELECT 'Rolled back' AS done;
