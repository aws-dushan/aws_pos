-- One POS: RPO50 2395 (One POS repacking INV-EBL-01-000004, ERBQS) was deleted in FACTS after it had been posted, but its stock stayed:
--   CAPPUCCINO 502113 +1 (batch RPO50-2395-1), COFFEE BEAN 505302 -0.020 (GRN50-12347-2), MILK FRESH 502901 -0.160 (GRN50-13354-1).
-- This removes them exactly as FACTS' own Cancel Posting does (usp_RPRV_APPR_CancelStockApproval): the voucher's stock lines, the batch
-- it made and that batch's job. No account entries were made for it. Nothing else used batch RPO50-2395-1 (checked 20-10-2026).
BEGIN TRANSACTION;

SELECT 'before' AS step, STTRN_DOCSRNO, STTRN_STOCK_DOCNO, STTRN_QTY, STTRN_BATCH_DOCNO FROM dbo.STOCK_TRANSACTION
WHERE STTRN_FYCODE = 'CFY' AND STTRN_DOCTYPE = 'RPO50' AND STTRN_DOCNO = '2395';

IF EXISTS (SELECT 1 FROM dbo.REPACKING_HEADER WHERE REP_DOCTYPE = 'RPO50' AND REP_DOCNO = '2395')
   OR EXISTS (SELECT 1 FROM dbo.STOCK_TRANSACTION WHERE STTRN_BATCH_DOCNO = 'RPO50-2395-1' AND NOT (STTRN_DOCTYPE = 'RPO50' AND STTRN_DOCNO = '2395'))
BEGIN
    ROLLBACK TRANSACTION;
    SELECT 'Stopped: RPO50 2395 exists again, or its batch was used. Nothing changed.' AS result;
    RETURN;
END

DELETE FROM dbo.STOCK_TRANSACTION WHERE STTRN_FYCODE = 'CFY' AND STTRN_DOCTYPE = 'RPO50' AND STTRN_DOCNO = '2395';
DELETE FROM dbo.STOCK_BATCH_MASTER WHERE BATMST_SFYCODE = 'CFY' AND BATMST_SDOCTYPE = 'RPO50' AND BATMST_SDOCNO = '2395';
DELETE FROM dbo.JOB_MASTER WHERE JOBMST_PREVIOUS_FYCODE = 'CFY' AND JOBMST_PREVIOUS_DOCTYPE = 'RPO50' AND JOBMST_PREVIOUS_DOCNO = '2395';

SELECT 'after' AS step, COUNT(*) AS stock_lines_left FROM dbo.STOCK_TRANSACTION WHERE STTRN_FYCODE = 'CFY' AND STTRN_DOCTYPE = 'RPO50' AND STTRN_DOCNO = '2395';
COMMIT TRANSACTION;
SELECT 'Done: RPO50 2395 stock removed.' AS result;
