-- One POS: RPO50 2395 and 2396 (20-10-2026, ERBQS) were posted before the repacked item's expiry was set to the voucher's date.
-- Sets it now on the IN lines and on the batches they made (RPO50-2395-1, RPO50-2396-1), as usp_ONEPOS_PostRepacking now does.
BEGIN TRANSACTION;

UPDATE i SET REPIDET_EXPIRY_DATE = CAST(h.REP_DOCDATE AS DATE)
FROM dbo.REPACKING_DETAILS_IN i
JOIN dbo.REPACKING_HEADER h ON h.REP_FYCODE = i.REPIDET_FYCODE AND h.REP_DOCTYPE = i.REPIDET_DOCTYPE AND h.REP_DOCNO = i.REPIDET_DOCNO
WHERE h.REP_FYCODE = 'CFY' AND h.REP_DOCTYPE = 'RPO50' AND h.REP_DOCNO IN ('2395', '2396') AND h.REP_NARRATION LIKE N'One POS repacking %';

UPDATE b SET BATMST_EXPIRY_DATE = CAST(h.REP_DOCDATE AS DATE)
FROM dbo.STOCK_BATCH_MASTER b
JOIN dbo.REPACKING_HEADER h ON h.REP_FYCODE = b.BATMST_SFYCODE AND h.REP_DOCTYPE = b.BATMST_SDOCTYPE AND h.REP_DOCNO = b.BATMST_SDOCNO
WHERE h.REP_FYCODE = 'CFY' AND h.REP_DOCTYPE = 'RPO50' AND h.REP_DOCNO IN ('2395', '2396') AND h.REP_NARRATION LIKE N'One POS repacking %';

SELECT BATMST_DOCNO, BATMST_STOCK_DOCNO, BATMST_EXPIRY_DATE FROM dbo.STOCK_BATCH_MASTER WHERE BATMST_DOCNO IN ('RPO50-2395-1', 'RPO50-2396-1');
COMMIT TRANSACTION;
