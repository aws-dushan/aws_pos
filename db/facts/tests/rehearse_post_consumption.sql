-- One POS: rehearse usp_ONEPOS_PostConsumption: 1 PCS of EB OUTLET - PISTACHIO CROISSANT W/FILLING (505486) given away for marketing
-- at Al Qusais (ERBQS), to 8003 SALES PROMOTION EXPENSES, posted as MalikaT (change @User to the FACTS user set as "Posted in FACTS
-- as"; it must be allowed MCV50 Transaction Posting). Everything is rolled back at the end: no MCV50 stays, no stock or accounts move,
-- the MCV50 last number is unchanged. Run after creating the procedure.
DECLARE @User NVARCHAR(20) = N'MalikaT';
SET XACT_ABORT OFF;
BEGIN TRANSACTION;

EXEC dbo.usp_ONEPOS_PostConsumption @ClientID = @User, @BodyXML = N'<data><Consumption><DocDate>2026-10-26</DocDate><Location>ERBQS</Location><Account>8003</Account>
  <Reference>One POS marketing REHEARSAL</Reference>
  <Line><ItemType>SMBK</ItemType><ItemCode>505486</ItemCode><ItemName>EB OUTLET - PISTACHIO CROISSANT W/FILLING</ItemName><Qty>1</Qty><Unit>PCS</Unit></Line>
</Consumption></data>';

-- What it made (inside the transaction): the voucher, its batch lines at cost, the stock moves, the accounts, FACTS' approval and log.
SELECT JMAT_DOCNO, JMAT_NARRATION, JMAT_LOCATION_DOCNO, JMAT_NET_AMOUNT, JMAT_POSTED_BY, JMAT_POSTED_TS FROM dbo.JOB_MATERIAL_HEADER WHERE JMAT_DOCTYPE = 'MCV50' AND JMAT_NARRATION = N'One POS marketing REHEARSAL';
SELECT d.JMATDET_DOCSRNO, d.JMATDET_STOCK_DOCNO, d.JMATDET_QTY, d.JMATDET_UNIT_DOCNO, d.JMATDET_BATCH_DOCNO, d.JMATDET_RATE, d.JMATDET_AMOUNT, d.JMATDET_AC_DOCNO FROM dbo.JOB_MATERIAL_DETAILS d
JOIN dbo.JOB_MATERIAL_HEADER h ON h.JMAT_FYCODE = d.JMATDET_FYCODE AND h.JMAT_DOCTYPE = d.JMATDET_DOCTYPE AND h.JMAT_DOCNO = d.JMATDET_DOCNO WHERE h.JMAT_DOCTYPE = 'MCV50' AND h.JMAT_NARRATION = N'One POS marketing REHEARSAL';
SELECT t.STTRN_DOCSRNO, t.STTRN_STOCK_DOCNO, t.STTRN_LOCATION_DOCNO, t.STTRN_QTY, t.STTRN_BATCH_DOCNO FROM dbo.STOCK_TRANSACTION t
JOIN dbo.JOB_MATERIAL_HEADER h ON h.JMAT_DOCTYPE = t.STTRN_DOCTYPE AND h.JMAT_DOCNO = t.STTRN_DOCNO WHERE h.JMAT_DOCTYPE = 'MCV50' AND h.JMAT_NARRATION = N'One POS marketing REHEARSAL';
SELECT a.ACTRN_DOCSRNO, a.ACTRN_AC_DOCNO, a.ACTRN_AMOUNT FROM dbo.ACCOUNT_TRANSACTION a
JOIN dbo.JOB_MATERIAL_HEADER h ON h.JMAT_DOCTYPE = a.ACTRN_DOCTYPE AND h.JMAT_DOCNO = a.ACTRN_DOCNO WHERE h.JMAT_DOCTYPE = 'MCV50' AND h.JMAT_NARRATION = N'One POS marketing REHEARSAL';
SELECT a.ACTION_DOCNO, a.ACTION_KEY, a.ACTION_TYPE, a.ACTION_USER_DOCNO FROM dbo.ACTION_STATUS a
JOIN dbo.JOB_MATERIAL_HEADER h ON h.JMAT_DOCTYPE = a.ACTION_DOCTYPE AND h.JMAT_DOCNO = a.ACTION_DOCNO WHERE h.JMAT_DOCTYPE = 'MCV50' AND h.JMAT_NARRATION = N'One POS marketing REHEARSAL';

IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
SELECT 'Rolled back' AS done;
