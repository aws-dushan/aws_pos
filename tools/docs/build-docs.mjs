// API: every Map{Get,Post,Put,Delete,Patch}("…") with the permission keys required in the lines that follow it.
function apiReference() {
  const rows = [];
  for (const file of walk(api)) {
    const lines = readFileSync(file, "utf8").split("\n");
    lines.forEach((line, i) => {
      for (const m of line.matchAll(/\.Map(Get|Post|Put|Delete|Patch)\("([^"]*)"/g)) {
        const body = lines.slice(i, i + 40).join("\n").slice(m.index + m[0].length);
        const next = body.search(/\.Map(Get|Post|Put|Delete|Patch)\(/);
        const scope = next < 0 ? body : body.slice(0, next);
        const perms = [...new Set([...scope.matchAll(/\b(?:Require|Can)\w*\(([^)]*)\)/g)].flatMap((r) => [...r[1].matchAll(/"([a-z]+\.[a-z_]+)"/g)].map((p) => p[1])))];
        const path = m[2].startsWith("/api/") || file.endsWith("Program.cs") ? m[2] : `/api${m[2]}`;
        rows.push({ method: m[1].toUpperCase(), path, perms: perms.join(", "), file: relative(root, file).replaceAll("\\", "/"), line: i + 1 });
      }
    });
  }
  rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  const area = (p) => p.replace(/^\/api/, "").split("/")[1] || "(root)";
  let md = `# API reference\n\n${generated}${rows.length} endpoints. Paths in \`Platform/\`, \`Pos/\` and \`Erp/\` sit under \`/api\` and need a signed-in user unless the code says otherwise; "Checks" lists the permission keys named in the handler (empty = signed in only, or checked in a helper).\n`;
  for (const a of [...new Set(rows.map((r) => area(r.path)))]) {
    md += `\n## ${a}\n\n| Method | Path | Checks | Source |\n| --- | --- | --- | --- |\n`;
    for (const r of rows.filter((r) => area(r.path) === a)) md += `| ${r.method} | \`${r.path}\` | ${r.perms} | ${r.file}:${r.line} |\n`;
  }
  return md;
}

